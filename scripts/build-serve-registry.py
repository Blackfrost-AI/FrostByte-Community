#!/usr/bin/env python3
"""Build src/shared/serve-registry.js: which HF `config.architectures` vLLM and SGLang can serve.

The snapshot is bundled at build time so FrostByte never queries a third party at runtime.
Usage: python3 scripts/build-serve-registry.py <vllm registry.py> <vllm commit> <sglang models dir> <sglang commit>
  vllm registry.py : vllm/model_executor/models/registry.py
  sglang models dir: python/sglang/srt/models
"""
import ast
import json
import pathlib
import sys

# vLLM dictionaries that map architecture -> implementation and mean "this can be served".
VLLM_TABLES = {
    '_TEXT_GENERATION_MODELS': 'generate',
    '_MULTIMODAL_MODELS': 'generate',
    '_EMBEDDING_MODELS': 'pooling',
    '_LATE_INTERACTION_MODELS': 'pooling',
    '_REWARD_MODELS': 'pooling',
    '_TOKEN_CLASSIFICATION_MODELS': 'pooling',
    '_SEQUENCE_CLASSIFICATION_MODELS': 'pooling',
    '_TRANSFORMERS_SUPPORTED_MODELS': 'generate',
}


def vllm_architectures(source):
    tree = ast.parse(source)
    found = {}
    for node in tree.body:
        targets = node.targets if isinstance(node, ast.Assign) else [node.target] if isinstance(node, ast.AnnAssign) else []
        for target in targets:
            if isinstance(target, ast.Name) and target.id in VLLM_TABLES and isinstance(node.value, ast.Dict):
                for key in node.value.keys:
                    if isinstance(key, ast.Constant) and isinstance(key.value, str):
                        found.setdefault(key.value, VLLM_TABLES[target.id])
    return found


def sglang_architectures(models_dir):
    found = set()
    for path in sorted(pathlib.Path(models_dir).glob('*.py')):
        try:
            tree = ast.parse(path.read_text(encoding='utf-8'))
        except SyntaxError:
            continue
        for node in tree.body:
            if not isinstance(node, ast.Assign):
                continue
            if not any(isinstance(t, ast.Name) and t.id == 'EntryClass' for t in node.targets):
                continue
            values = node.value.elts if isinstance(node.value, (ast.List, ast.Tuple)) else [node.value]
            for value in values:
                if isinstance(value, ast.Name):
                    found.add(value.id)
                elif isinstance(value, ast.Attribute):
                    found.add(value.attr)
    return found


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    vllm_file, vllm_commit, sglang_dir, sglang_commit = sys.argv[1:]
    vllm = vllm_architectures(pathlib.Path(vllm_file).read_text(encoding='utf-8'))
    sglang = sglang_architectures(sglang_dir)
    if len(vllm) < 100 or len(sglang) < 100:
        sys.exit(f'Refusing to write a suspiciously small registry (vllm={len(vllm)}, sglang={len(sglang)}).')
    out = {
        'schema': 'frostbyte.serve-registry',
        'version': 1,
        'sources': {
            'vllm': {'repo': 'vllm-project/vllm', 'commit': vllm_commit, 'path': 'vllm/model_executor/models/registry.py'},
            'sglang': {'repo': 'sgl-project/sglang', 'commit': sglang_commit, 'path': 'python/sglang/srt/models/*.py (EntryClass)'},
        },
        'vllm': {arch: vllm[arch] for arch in sorted(vllm)},
        'sglang': sorted(sglang),
    }
    target = pathlib.Path(__file__).resolve().parent.parent / 'src/shared/serve-registry.js'
    header = ('// GENERATED by scripts/build-serve-registry.py. Do not edit by hand.\n'
              '// Architectures vLLM and SGLang can serve, snapshotted at the commits below (no runtime lookups).\n')
    target.write_text(header + 'export default ' + json.dumps(out, indent=1) + ';\n', encoding='utf-8')
    print(f'wrote {target} vllm={len(vllm)} sglang={len(sglang)}')


if __name__ == '__main__':
    main()
